import { spawnSync } from 'node:child_process';
import process from 'node:process';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const commands = new Map([
  ['check', ['check', '--manifest-path', 'src-tauri/Cargo.toml']],
  ['clippy', ['clippy', '--manifest-path', 'src-tauri/Cargo.toml', '--all-targets', '--', '-D', 'warnings']],
]);

const commandName = process.argv[2];
const cargoArguments = commands.get(commandName);
if (!cargoArguments) {
  throw new Error(`未知的 Rust 质量检查：${commandName || 'missing'}`);
}

let inlineConfig = {};
const configured = process.env.TAURI_CONFIG?.trim();
if (configured) {
  inlineConfig = JSON.parse(configured);
  if (!inlineConfig || typeof inlineConfig !== 'object' || Array.isArray(inlineConfig)) {
    throw new Error('TAURI_CONFIG 必须是 JSON object');
  }
}

const bundle = inlineConfig.bundle && typeof inlineConfig.bundle === 'object' && !Array.isArray(inlineConfig.bundle)
  ? inlineConfig.bundle
  : {};
const resources = bundle.resources && typeof bundle.resources === 'object' && !Array.isArray(bundle.resources)
  ? bundle.resources
  : {};
const qualityConfig = {
  ...inlineConfig,
  bundle: {
    ...bundle,
    // These five macOS installer resources are generated by Tauri's
    // beforeBuildCommand. Direct Cargo quality checks do not run that hook.
    // Null removes only these keys through JSON Merge Patch; checked-in and
    // lightweight generated legal/product resources remain validated.
    resources: {
      ...resources,
      'target/yunspire-runtime/macos-python/': null,
      'target/yunspire-native/macos/yunspire-media': null,
      'target/yunspire-native/macos/yunspire-pdf': null,
      'target/yunspire-native/macos/Yunspire Speech Helper.app/': null,
      'target/yunspire-native/macos/helpers-manifest.json': null,
    },
  },
};

console.log(`NATIVE_QUALITY_CONFIG command=${commandName} macos_generated_resources=disabled`);
const result = spawnSync('cargo', cargoArguments, {
  cwd: root,
  env: {
    ...process.env,
    TAURI_CONFIG: JSON.stringify(qualityConfig),
  },
  stdio: 'inherit',
});

if (result.error) throw result.error;
if (result.signal) throw new Error(`cargo ${commandName} 被信号 ${result.signal} 终止`);
process.exit(result.status ?? 1);
